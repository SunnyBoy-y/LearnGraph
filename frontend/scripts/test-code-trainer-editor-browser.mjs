import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { join } from "node:path";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const require=createRequire(import.meta.url);
let pw; try {pw=require('playwright')} catch {pw=require(join(process.env.APPDATA,'npm/node_modules/@playwright/cli/node_modules/playwright'))}
const browser=await pw.chromium.launch({headless:true,executablePath:process.env.CODE_TRAINER_CHROMIUM||join(process.env.LOCALAPPDATA,'ms-playwright/chromium-1243/chrome-win64/chrome.exe')});
try {
  const page=await browser.newPage({viewport:{width:1280,height:1000},permissions:['clipboard-read','clipboard-write']}), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.env.CODE_TRAINER_EDITOR_URL||'http://127.0.0.1:5207/code-trainer.html');
  const editor=page.getByRole('textbox',{name:'代码编辑器',exact:true});
  await editor.waitFor({timeout:60000});
  const text=()=>page.evaluate(async()=>{const resource=performance.getEntriesByType('resource').map(x=>x.name).find(url=>/\/assets\/code-trainer-monaco-[^/]+\.js/.test(url));const {monaco}=await import(resource??'/src/lib/code-trainer-monaco.ts');return monaco.editor.getModels()[0].getValue()});
  const replace=async(value,target=editor)=>{await target.focus();await page.keyboard.press('Control+a');if(value){await page.evaluate(value=>navigator.clipboard.writeText(value),value);await page.keyboard.press('Control+v')}else await page.keyboard.press('Backspace');await page.keyboard.press('Escape');for(let i=0;i<20&&await text()!==value;i++)await page.waitForTimeout(100);assert.equal(await text(),value)};
  const original=await text();
  await page.getByRole('checkbox',{name:'智能补全'}).uncheck();
  await replace('');await editor.focus();await page.keyboard.type('imp',{delay:120});
  await page.getByRole('listitem',{name:'import, Keyword',exact:true}).waitFor();
  await page.keyboard.press('Tab');assert.equal(await text(),'import');
  console.log('PASS keyword completion and Tab work with smart completion off');
  await replace('\n');await page.keyboard.press('Tab');assert.match(await text(),/^\n {2,4}$/);
  await page.getByRole('checkbox',{name:'智能补全'}).check();
  await replace('');await editor.focus();await page.keyboard.type('pri',{delay:120});
  await page.getByRole('listitem',{name:/print, Function/}).waitFor();
  await page.keyboard.press('Tab');assert.equal(await text(),'print');
  console.log('PASS smart completion adds Python builtins');
  await replace(original);
  await page.waitForFunction(()=>new Set([...document.querySelectorAll('.view-lines span')].filter(el=>el.textContent?.trim()).map(el=>getComputedStyle(el).color)).size>=2);
  const colors=await page.locator('.view-lines span').evaluateAll(elements=>[...new Set(elements.filter(el=>el.textContent?.trim()).map(el=>getComputedStyle(el).color))]);
  assert.ok(colors.length>=2);console.log('PASS colored syntax',colors);
  await page.getByRole('button',{name:'左右分屏',exact:true}).click();
  await page.waitForTimeout(300);
  assert.equal(await page.locator('.code-ide .monaco-editor').count(),1);
  const problem=page.getByRole('complementary',{name:'题目与公开样例'});
  await problem.waitFor();assert.ok((await problem.innerText()).includes('公开样例'));
  const problemBox=await problem.boundingBox(), editorBox=await page.locator('.code-ide__pane').boundingBox();
  assert.ok(problemBox.x+problemBox.width<=editorBox.x+1,'problem is left of code editor');
  assert.equal(await text(),original);
  await replace(`${original}\n# editing in split`);
  await editor.focus();await page.keyboard.press('Control+z');
  assert.notEqual(await text(),`${original}\n# editing in split`);console.log('PASS left problem, right single code editor; source and undo preserved');
  await replace(Array.from({length:60},(_,i)=>`# line ${i} ${'x'.repeat(220)}`).join('\n'));
  assert.ok(await page.locator('.code-ide__pane').first().locator('.editor-scrollable > .scrollbar.vertical').isVisible());
  assert.ok(await page.locator('.code-ide__pane').first().locator('.editor-scrollable > .scrollbar.horizontal').isVisible());
  console.log('PASS vertical and horizontal scrollbars');
  await replace(original);
  await page.getByRole('button',{name:'全屏',exact:true}).click();
  assert.ok(await page.locator('.code-ide').evaluate(el=>el.matches(':popover-open')&&el.getBoundingClientRect().width>innerWidth-32));
  const output=fileURLToPath(new URL('../../docs/',import.meta.url));await mkdir(output,{recursive:true});
  await page.screenshot({path:join(output,'code-trainer-ide-fullscreen.png'),fullPage:true});
  await page.getByRole('button',{name:'退出全屏',exact:true}).click();
  await page.getByRole('button',{name:'关闭分屏',exact:true}).click();await replace(original);
  assert.equal(await page.locator('.code-ide .monaco-editor').count(),1);
  await page.locator('section.code-trainer').screenshot({path:join(output,'code-trainer-ide.png')});
  assert.deepEqual(errors,[]);console.log('PASS fullscreen, exit and close split preserve source; no page errors');
}finally{await browser.close()}
