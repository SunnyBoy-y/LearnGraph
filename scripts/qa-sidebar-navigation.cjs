const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const packageBin = process.env.PATH.split(path.delimiter).find(dir => fs.existsSync(path.resolve(dir, '../playwright/package.json')));
if (!packageBin) throw new Error('Run with npx --package=playwright');
const { chromium } = require(path.resolve(packageBin, '../playwright'));
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1.5, reducedMotion: 'reduce' });
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const url = `${process.env.SIDEBAR_QA_URL || 'http://127.0.0.1:15173'}/sidebar-navigation-qa.html`;
  const desktop = () => page.locator('.sidebar-nav').filter({ has: page.locator('[data-sidebar-toggle]') }).first();
  const search = async sidebar => {
    await sidebar.getByRole('button', { name: '搜索文件、会话和消息', exact: true }).click();
    await page.getByRole('dialog', { name: '搜索工作区' }).waitFor();
    await page.getByRole('textbox', { name: '搜索文件、会话、消息或 ID' }).fill('TCP');
    await page.locator('[data-search-result]').first().waitFor();
  };
  const groupChecks = async sidebar => {
    const projectFolder = sidebar.locator('[data-virtual-key="project:p1"] .sidebar-project__folder-toggle');
    const folderWasOpen = await projectFolder.getAttribute('aria-expanded');
    await sidebar.getByRole('button', { name: '折叠项目分组', exact: true }).click();
    assert.equal(await sidebar.locator('[data-virtual-key="project:p1"]').count(), 0);
    assert.equal(await sidebar.getByRole('button', { name: '折叠最近分组', exact: true }).isVisible(), true);
    await sidebar.getByRole('button', { name: '折叠最近分组', exact: true }).focus();
    await page.keyboard.press('Enter');
    assert.equal(await sidebar.locator('[data-virtual-key="session:recent-0"]').count(), 0);
    await sidebar.getByRole('button', { name: '展开项目分组', exact: true }).focus();
    await page.keyboard.press('Space');
    assert.equal(await projectFolder.getAttribute('aria-expanded'), folderWasOpen);
    await sidebar.getByRole('button', { name: '展开最近分组', exact: true }).click();
    await sidebar.locator('[data-virtual-key="session:recent-0"]').waitFor();
  };
  try {
    await page.goto(url);
    let sidebar = desktop();
    await sidebar.getByRole('button', { name: '折叠项目分组', exact: true }).waitFor();
    await sidebar.locator('[data-virtual-key="session:tcp"]').waitFor();
    assert.equal(await sidebar.getByText('会话', { exact: true }).count(), 0);
    assert.equal(await sidebar.locator('.sidebar-sessions .lucide-chevron-down, .sidebar-sessions .lucide-chevron-right').count(), 0);
    const top = sidebar.locator('.sidebar-nav__top');
    const box = await top.boundingBox();
    const controls = await top.locator('a,button').evaluateAll(els => els.filter(el => el.getBoundingClientRect().width).map(el => { const r = el.getBoundingClientRect(); return { label: el.getAttribute('aria-label') || el.textContent, left: r.left, right: r.right }; }));
    assert.ok(controls.every(r => r.left >= box.x - 1 && r.right <= box.x + box.width + 1), JSON.stringify({ box, controls }));
    const iconColors = await sidebar.locator('[data-nav-label] > svg').evaluateAll(els => [...new Set(els.map(el => getComputedStyle(el).color))]);
    assert.equal(iconColors.length, 1, iconColors.join(','));
    const project = sidebar.locator('[data-virtual-key="project:p1"]');
    await project.hover();
    const neutral = await project.locator('.sidebar-project__heading').evaluate(el => ({ background: getComputedStyle(el).backgroundColor, shadow: getComputedStyle(el).boxShadow }));
    assert.deepEqual(neutral, { background: 'rgba(0, 0, 0, 0)', shadow: 'none' });
    assert.notEqual(await sidebar.locator('.sidebar-project__session.is-active').evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
    await project.getByRole('button', { name: '选择项目 计算机网络' }).click();
    assert.equal(await project.getByRole('button', { name: '折叠文件夹 计算机网络' }).getAttribute('aria-expanded'), 'true');
    await project.getByRole('button', { name: '管理项目 计算机网络' }).click();
    await page.getByRole('menuitem', { name: '改名', exact: true }).waitFor();
    await sidebar.locator('.sidebar-nav__scroll').evaluate(el => new Promise(resolve => { el.scrollTop = el.scrollHeight; requestAnimationFrame(() => requestAnimationFrame(resolve)); }));
    assert.equal(await page.getByRole('menuitem', { name: '改名', exact: true }).isVisible(), true, 'Project menu must survive virtual scrolling');
    await sidebar.locator('.sidebar-nav__scroll').evaluate(el => { el.scrollTop = 0; });
    await page.keyboard.press('Escape');
    await page.mouse.move(1100, 100);
    await page.screenshot({ path: 'artifacts/sidebar-preview-2026-11-15/production-desktop.png' });
    await groupChecks(sidebar);
    await sidebar.getByRole('button', { name: '折叠项目分组', exact: true }).click();
    await page.reload();
    sidebar = desktop();
    await sidebar.getByRole('button', { name: '展开项目分组', exact: true }).waitFor();
    await sidebar.getByRole('button', { name: '新建项目', exact: true }).click();
    await sidebar.getByRole('textbox', { name: '项目名称', exact: true }).fill('浏览器验收项目');
    await sidebar.getByRole('button', { name: '确认新建项目', exact: true }).click();
    await sidebar.getByRole('button', { name: '选择项目 浏览器验收项目', exact: true }).waitFor();
    await sidebar.getByRole('button', { name: '管理项目分组', exact: true }).focus();
    await page.keyboard.press('Enter');
    await page.getByRole('menuitem', { name: '批量管理', exact: true }).click();
    await sidebar.getByRole('checkbox', { name: '选择项目 计算机网络', exact: true }).check();
    await sidebar.getByRole('button', { name: '管理项目分组', exact: true }).focus();
    await page.keyboard.press('Enter');
    await page.getByRole('menuitem', { name: '退出批量管理', exact: true }).click();
    assert.equal(await sidebar.getByRole('checkbox').count(), 0);
    await search(sidebar);
    await page.getByRole('textbox', { name: '搜索文件、会话、消息或 ID' }).fill('没有结果的关键词');
    await page.getByRole('status').filter({ hasText: '没有找到相关结果' }).waitFor();
    await page.getByRole('button', { name: '关闭搜索', exact: true }).click();
    await sidebar.getByRole('button', { name: '折叠侧边栏', exact: true }).click();
    await search(sidebar);
    await page.keyboard.press('Escape');
    await sidebar.getByRole('button', { name: '展开侧边栏', exact: true }).click();
    for (const [label, route] of [['图谱','graphs'],['资料','sources'],['产物','artifacts'],['定时任务','schedules']]) {
      await sidebar.getByRole('link', { name: label, exact: true }).click();
      await page.waitForFunction(route => window.__sidebarNavigationQA.route.endsWith('/' + route), route);
      assert.equal(await sidebar.getByRole('button', { name: '搜索文件、会话和消息', exact: true }).isVisible(), true);
      assert.equal(await sidebar.getByRole('button', { name: '折叠项目分组', exact: true }).getAttribute('aria-expanded'), 'true');
      const colors = await sidebar.locator('[data-nav-label] > svg').evaluateAll(els => [...new Set(els.map(el => getComputedStyle(el).color))]);
      assert.equal(colors.length, 1);
    }
    for (const label of ['练习','记忆']) {
      await sidebar.getByRole('button', { name: '更多', exact: true }).click();
      await page.getByRole('menuitem', { name: label, exact: true }).click();
      await page.waitForFunction(route => window.__sidebarNavigationQA.route.endsWith('/' + route), label === '练习' ? 'practice' : 'memory');
      await sidebar.getByRole('button', { name: '搜索文件、会话和消息', exact: true }).waitFor();
    }
    await search(sidebar);
    await page.getByRole('button', { name: '文件', exact: true }).click();
    await page.getByRole('textbox', { name: '搜索文件、会话、消息或 ID' }).fill('');
    await page.locator('[data-search-result]').first().click();
    await page.waitForFunction(() => window.__sidebarNavigationQA.route.endsWith('/documents/file-1'));
    await page.evaluate(() => document.documentElement.classList.add('dark'));
    await sidebar.getByRole('link', { name: '图谱', exact: true }).click();
    await sidebar.getByRole('button', { name: '选择项目 计算机网络' }).hover();
    assert.equal(await sidebar.locator('[data-nav-label] > svg').evaluateAll(els => new Set(els.map(el => getComputedStyle(el).color)).size), 1);
    assert.equal(await sidebar.locator('.sidebar-project__heading').first().evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
    await page.mouse.move(1100, 100);
    await page.screenshot({ path: 'artifacts/sidebar-preview-2026-11-15/production-dark.png' });
    await page.evaluate(() => document.documentElement.classList.remove('dark'));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: '打开导航', exact: true }).click();
    const mobile = page.locator('.sidebar-nav.is-mobile');
    await mobile.getByRole('button', { name: '折叠项目分组', exact: true }).waitFor();
    await groupChecks(mobile);
    await mobile.getByRole('button', { name: '管理项目分组', exact: true }).click();
    await page.getByRole('menuitem', { name: '批量管理', exact: true }).waitFor();
    await page.keyboard.press('Escape');
    await search(mobile);
    await page.getByRole('button', { name: '关闭搜索', exact: true }).click();
    await mobile.getByRole('button', { name: '搜索文件、会话和消息', exact: true }).waitFor();
    await search(mobile);
    const dialogBox = await page.getByRole('dialog', { name: '搜索工作区' }).boundingBox();
    assert.ok(dialogBox.x >= -1 && dialogBox.x + dialogBox.width <= 391, JSON.stringify(dialogBox));
    await page.locator('[data-search-result]').first().click();
    await page.waitForFunction(() => window.__sidebarNavigationQA.route.endsWith('/chat/tcp'));
    await page.waitForFunction(() => !document.querySelector('.sidebar-nav.is-mobile')?.closest('[role="dialog"]') || document.querySelector('.sidebar-nav.is-mobile').closest('[role="dialog"]').getAttribute('aria-hidden') === 'true');
    await page.getByRole('button', { name: '打开导航', exact: true }).click();
    await mobile.getByRole('button', { name: '折叠项目分组', exact: true }).waitFor();
    await page.waitForFunction(() => { const drawer = document.querySelector('.mobile-nav-drawer.is-open'); return drawer && getComputedStyle(drawer).opacity === '1'; });
    await page.mouse.move(380, 50);
    await page.screenshot({ path: 'artifacts/sidebar-preview-2026-11-15/production-mobile.png', animations: 'disabled' });
    await mobile.locator('.sidebar-nav__scroll').evaluate(el => { el.scrollTop = 500; });
    assert.equal(await mobile.locator('.sidebar-nav__search').isVisible(), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.keyboard.press('Escape');
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ pass: true, checks: ['top search including collapsed sidebar', 'brand and controls fit', 'neutral icons on all navigation routes', 'no triangles', 'transparent project rows', 'selected session retained', 'independent section collapse and reload persistence', 'keyboard disclosure', 'new project after collapse', 'batch selection and exit', 'search empty state', 'chat and file search navigation', 'mobile search closes drawer', 'mobile section menus and scroll', 'dark theme', 'no page errors'], images: ['production-desktop.png','production-dark.png','production-mobile.png'] }, null, 2));
  } catch (error) {
    console.error('STATE', JSON.stringify(await page.evaluate(() => ({ route: window.__sidebarNavigationQA?.route, text: document.body.innerText.slice(0, 7000) }))), errors);
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
