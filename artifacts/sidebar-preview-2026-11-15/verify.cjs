const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const packageBin = process.env.PATH.split(path.delimiter).find(dir => fs.existsSync(path.resolve(dir, '../playwright/package.json')));
if (!packageBin) throw new Error('Run using npx --package=playwright');
const { chromium } = require(path.resolve(packageBin, '../playwright'));
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1000, height: 1100 }, deviceScaleFactor: 2 });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const groupChecks = async sidebar => {
    const projects = sidebar.locator('.projects');
    const recent = sidebar.locator('.recent-list');
    await sidebar.getByRole('button', { name: '折叠项目分组', exact: true }).click();
    assert.equal(await projects.isVisible(), false);
    assert.equal(await recent.isVisible(), true);
    await sidebar.getByRole('button', { name: '折叠最近分组', exact: true }).click();
    assert.equal(await projects.isVisible(), false);
    assert.equal(await recent.isVisible(), false);
    await sidebar.getByRole('button', { name: '展开项目分组', exact: true }).focus();
    await page.keyboard.press('Enter');
    assert.equal(await projects.isVisible(), true);
    assert.equal(await recent.isVisible(), false);
    await sidebar.getByRole('button', { name: '展开最近分组', exact: true }).focus();
    await page.keyboard.press('Space');
    assert.equal(await recent.isVisible(), true);
    assert.equal(await sidebar.getByRole('button', { name: '收起项目 计算机网络', exact: true }).getAttribute('aria-expanded'), 'true');
    assert.equal(await sidebar.locator('.children .session.active').isVisible(), true);
  };
  try {
    await page.goto('http://127.0.0.1:5217/');
    await page.evaluate(() => document.fonts.ready);
    const sidebar = page.locator('.sidebar').first();
    assert.equal(await sidebar.locator('.top-search').isVisible(), true);
    assert.equal(await sidebar.locator('.project-row').nth(1).locator('.row-actions').isVisible(), false);
    const hoveredRow = page.locator('.sidebar').nth(1).locator('.project-row').nth(1);
    assert.equal(await hoveredRow.locator('.row-actions').isVisible(), true);
    assert.equal(await hoveredRow.evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
    assert.notEqual(await sidebar.locator('.session.active').evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
    assert.equal(await page.evaluate(() => /[▸▾▶▼]/.test(document.body.innerText)), false);
    await page.screenshot({ path: path.join(__dirname, 'sidebar-preview-v2.png'), fullPage: true });
    await groupChecks(sidebar);
    await sidebar.getByRole('button', { name: '搜索会话、文件和消息' }).click();
    await page.getByRole('textbox', { name: '搜索', exact: true }).fill('TCP');
    assert.equal(await page.locator('.results button').count(), 1);
    await page.getByRole('textbox', { name: '搜索', exact: true }).fill('没有这个会话');
    assert.equal(await page.locator('.empty').isVisible(), true);
    await page.keyboard.press('Escape');
    await sidebar.getByRole('button', { name: '收起项目 计算机网络' }).click();
    assert.equal(await sidebar.locator('.project').nth(1).locator('.children').isVisible(), false);
    await sidebar.getByRole('button', { name: '展开项目 计算机网络' }).click();
    await sidebar.locator('.project-title').nth(1).click();
    assert.equal(await sidebar.locator('.project').nth(1).locator('.children').isVisible(), true);
    await sidebar.locator('.project-row').nth(1).hover();
    assert.equal(await sidebar.locator('.project-row').nth(1).evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
    await sidebar.getByRole('button', { name: '管理项目 计算机网络' }).click();
    assert.equal(await page.getByRole('menuitem', { name: '重命名', exact: true }).isVisible(), true);
    await page.keyboard.press('Escape');
    await sidebar.getByRole('button', { name: '折叠项目分组', exact: true }).click();
    await sidebar.getByRole('button', { name: '新建项目', exact: true }).click();
    assert.equal(await sidebar.locator('.projects').isVisible(), true);
    await sidebar.getByRole('textbox', { name: '项目名称' }).fill('测试项目');
    await sidebar.locator('.project-create button').click();
    assert.equal(await sidebar.getByRole('button', { name: '测试项目', exact: true }).isVisible(), true);
    await page.reload();
    await sidebar.getByRole('button', { name: '折叠项目分组', exact: true }).click();
    await page.locator('.sidebar').nth(1).getByRole('button', { name: '折叠最近分组', exact: true }).click();
    await page.evaluate(() => {
      const labels = document.querySelectorAll('.state-label');
      labels[0].textContent = '项目收起 · 最近展开';
      labels[1].textContent = '项目展开 · 最近收起';
      document.querySelector('.board h1').textContent = '两个分组，各自展开与收起';
      document.querySelector('.intro').textContent = '直接点击“项目”或“最近” · 不增加三角箭头 · 保留内部展开状态';
      document.activeElement.blur();
    });
    await page.mouse.move(980, 1080);
    await page.screenshot({ path: path.join(__dirname, 'groups-folding-v2.png'), fullPage: true });
    await page.goto('http://127.0.0.1:5217/?view=app');
    await page.setViewportSize({ width: 1360, height: 900 });
    await groupChecks(page.locator('.sidebar'));
    await page.keyboard.press('Control+k');
    assert.equal(await page.locator('dialog').isVisible(), true);
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: '折叠侧边栏' }).click();
    assert.equal(await page.locator('.sidebar').isVisible(), false);
    await page.getByRole('button', { name: '展开侧边栏' }).click();
    assert.equal(await page.locator('.sidebar').isVisible(), true);
    await page.setViewportSize({ width: 390, height: 844 });
    await groupChecks(page.locator('.sidebar'));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.getByRole('button', { name: '搜索会话、文件和消息' }).click();
    const dialogBox = await page.locator('dialog').boundingBox();
    assert.ok(dialogBox.x >= 0 && dialogBox.x + dialogBox.width <= 390);
    await page.keyboard.press('Escape');
    const scrollPosition = await page.locator('.sidebar .scroll').evaluate(el => { el.scrollTop = el.scrollHeight; return el.scrollTop; });
    assert.ok(scrollPosition > 0);
    assert.equal(await page.locator('.top-search').isVisible(), true);
    await page.getByRole('button', { name: '折叠侧边栏' }).click();
    await page.getByRole('button', { name: '展开侧边栏' }).click();
    await page.goto('http://127.0.0.1:5217/');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await groupChecks(page.locator('.sidebar').first());
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ pass: true, desktop: '1360x900', mobile: '390x844', checks: ['transparent parent on hover and focus', 'selected session background retained', 'independent group collapse in both views and viewport sizes', 'Enter and Space keyboard operation', 'nested folder and session state retained', 'new project expands collapsed group', 'search and empty results', 'object menus', 'sidebar collapse and expand', 'mobile scrolling and fixed search', 'no horizontal overflow', 'no triangle symbols', 'no page errors'], images: ['sidebar-preview-v2.png', 'groups-folding-v2.png'] }, null, 2));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
